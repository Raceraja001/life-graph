"""The owner's authority, written down: issued capabilities and standing rules.

A capability is proof the owner approved *one* action — a specific click, on a
specific element, at a specific step of a specific errand run. Until migration
059 the record lived in one process's memory, which failed closed over a
restart but meant the worker that minted a mandate had to be the worker that
executed it, and "one use" was one use *per process*.

These two tables are the shared version. They are written and read by
``autonomy/approvals/durable_store.py``, which deliberately uses raw SQL
rather than this ORM for the operation that matters: consumption is a single
``UPDATE … WHERE consumed_at IS NULL … RETURNING`` so that Postgres, not
Python, decides which of two racing workers gets to perform the action. The
models are here so that the schema is declared once, in the place every other
table is declared, and so ``Base.metadata`` — and therefore ``docs/STATE.md``
and any autogenerated migration — tells the truth about what exists.

Nothing in :class:`Capability` is a secret. ``parameters_hash`` is a SHA-256
over the canonicalised action (``services.browser_errand``), so the value the
owner approved can be *compared* but never read back out of the table.
"""

from __future__ import annotations

import uuid  # noqa: TC003
from datetime import datetime  # noqa: TC003
from decimal import Decimal  # noqa: TC003

from sqlalchemy import Boolean, DateTime, Index, Integer, Numeric, String, func, text
from sqlalchemy.dialects.postgresql import ARRAY, UUID
from sqlalchemy.orm import Mapped, mapped_column

from life_graph.models.base import Base


class Capability(Base):
    """One mandate the owner issued, with every binding it is re-tested against.

    Each nullable binding means "not scoped to one of these" rather than
    "matches nothing": a capability the owner issued for a transfer carries no
    ``errand_id``, and one minted from an errand approval carries all four. A
    binding that *is* set is compared strictly at execution time, so a caller
    that cannot assert it is refused
    (``autonomy/approvals/capability.AuthorizationCapability.check_bindings``).

    ``target_origins`` is ``NULL`` for "wherever" and is never the empty array
    — a capability authorising no origin can never fire, so the store refuses
    to issue one. The two are opposite meanings and the column keeps them
    apart.
    """

    __tablename__ = "capabilities"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    # The opaque handle that travels. Unique across tenants: it is 24 random
    # bytes, and a collision would let one tenant's handle name another's row.
    # It is also what makes the consuming UPDATE touch exactly one row.
    capability_id: Mapped[str] = mapped_column(String(64), nullable=False)
    tenant_id: Mapped[str] = mapped_column(String(64), nullable=False)
    task_id: Mapped[str | None] = mapped_column(String(64), nullable=True)
    # The errand run the owner saw the plan of, the notification they tapped,
    # and the step's position in that run.
    errand_id: Mapped[str | None] = mapped_column(String(64), nullable=True)
    approval_id: Mapped[str | None] = mapped_column(String(64), nullable=True)
    step_index: Mapped[int | None] = mapped_column(Integer, nullable=True)
    action_types: Mapped[list[str]] = mapped_column(
        ARRAY(String), nullable=False, server_default="{}"
    )
    target_origins: Mapped[list[str] | None] = mapped_column(ARRAY(String), nullable=True)
    # The element, and a digest of the whole action. Never the value.
    target_selector: Mapped[str | None] = mapped_column(String(255), nullable=True)
    parameters_hash: Mapped[str | None] = mapped_column(String(64), nullable=True)
    one_use: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("true"))
    # Stamped by the conditional UPDATE in durable_store.consume and nothing
    # else, which is what makes a replay and a race both lose.
    consumed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    revoked: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("false"))
    # How the server recognised the owner (device:<id>, owner:api_key), so an
    # audit trail names a credential and not the bare word "owner".
    actor: Mapped[str] = mapped_column(String(120), nullable=False, server_default="owner")
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    max_amount: Mapped[Decimal | None] = mapped_column(Numeric(18, 4), nullable=True)

    __table_args__ = (
        Index("uq_capabilities_capability_id", "capability_id", unique=True),
        Index("ix_capabilities_tenant", "tenant_id"),
        Index("ix_capabilities_tenant_errand", "tenant_id", "errand_id"),
        Index("ix_capabilities_tenant_task", "tenant_id", "task_id"),
        Index("ix_capabilities_expires_at", "expires_at"),
    )

    def __repr__(self) -> str:
        state = "revoked" if self.revoked else ("spent" if self.consumed_at else "live")
        return (
            f"<Capability(id={self.capability_id!s:.12}…, tenant={self.tenant_id!r}, "
            f"errand={self.errand_id!r}, step={self.step_index}, {state})>"
        )


class StandingRuleRecord(Base):
    """One lasting "always / never" the owner set, for one action and one origin.

    One row per ``(tenant, action_type, target_origin)`` so that "which effect
    applies" never depends on row order; a rule the owner wrote over three
    sites is three rows, and reading them back gives three single-origin rules
    matching exactly what the one rule matched. ``target_origin`` of ``NULL``
    is "this action, wherever it targets".

    Named ``StandingRuleRecord`` rather than ``StandingRule`` because the
    latter is the frozen dataclass the policy actually matches on
    (``autonomy/approvals/policy_checker.StandingRule``); only
    owner-authenticated code writes either, and
    ``request_from_payload`` drops any rule that arrives in a payload.
    """

    __tablename__ = "standing_rules"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    tenant_id: Mapped[str] = mapped_column(String(64), nullable=False)
    action_type: Mapped[str] = mapped_column(String(64), nullable=False)
    # allow | deny | require_approval (policy_checker.DECISIONS)
    effect: Mapped[str] = mapped_column(String(32), nullable=False)
    target_origin: Mapped[str | None] = mapped_column(String(255), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    __table_args__ = (
        Index("ix_standing_rules_tenant", "tenant_id"),
        # Partial, because NULLs are distinct in a unique index: the two
        # halves together are "one row per scope, any-origin included".
        Index(
            "uq_standing_rules_scope",
            "tenant_id",
            "action_type",
            "target_origin",
            unique=True,
            postgresql_where=text("target_origin IS NOT NULL"),
        ),
        Index(
            "uq_standing_rules_scope_any_origin",
            "tenant_id",
            "action_type",
            unique=True,
            postgresql_where=text("target_origin IS NULL"),
        ),
    )

    def __repr__(self) -> str:
        where = self.target_origin or "any origin"
        return f"<StandingRuleRecord({self.action_type}={self.effect} on {where})>"
